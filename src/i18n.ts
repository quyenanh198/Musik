export const messages: Record<Lang, Record<MessageKey, string>> = { en, vi };

/** Label for each repeat mode, for the tooltip "Repeat: all". */
export const REPEAT_LABEL_KEY = { off: 'repeat.off', all: 'repeat.all', one: 'repeat.one' } as const satisfies Record<string, MessageKey>;

export type Params = Record<string, string | number>;
export type Translate = (key: MessageKey, params?: Params) => string;

/**
 * The text for `key` in `lang`, with `{name}` placeholders filled from `params`. When `params.n` is 1 and a
 * `<key>_one` variant exists it is used, so English can say "1 track" (Vietnamese has one form for every count).
 */
export function translate(lang: Lang, key: MessageKey, params?: Params): string {
  const table = messages[lang] as Record<string, string>;
  const text = params?.n === 1 && `${key}_one` in table ? table[`${key}_one`] : table[key];
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));
}

/** A saved choice wins; otherwise Vietnamese browsers get Vietnamese and everyone else English. */
export function detectLang(saved: string | null, browserLanguage?: string): Lang {
  const chosen = LANGS.find((lang) => lang === saved);
  if (chosen) return chosen;
  return browserLanguage?.toLowerCase().startsWith('vi') ? 'vi' : 'en';
}
